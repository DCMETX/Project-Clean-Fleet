/* ---------------------------------------------------------------------------
   SEED DATA GENERATION — 22 weeks ending the most recent Monday, so
   "overdue" flags on corrective actions are always computed against the
   real current date, not a date frozen at build time.
   --------------------------------------------------------------------- */
function buildSeedData() {
  const rand = mulberry32(1337);
  const ri = (min, max) => Math.floor(rand() * (max - min + 1)) + min;
  const pick = arr => arr[ri(0, arr.length - 1)];
  const clamp = (v, a, b) => Math.max(a, Math.min(b, v));

  const WEEKS = 22;
  const start = addDays(mostRecentMonday(new Date()), -WEEKS * 7);

  const inspections = [];
  const carPool = {};
  DISTRICTS.forEach(d => {
    carPool[d.id] = REAL_CAR_ROSTERS[d.id]
      ? REAL_CAR_ROSTERS[d.id]
      : Array.from({ length: 14 }, () => `${d.id}-${ri(4000, 9999)}`);
  });

  let idCounter = 1;
  for (let w = 0; w < WEEKS; w++) {
    const weekStart = addDays(start, w * 7);
    DISTRICTS.forEach(d => {
      SHIFTS.forEach(shift => {
        // 1-2 inspections per district/shift/week
        const n = rand() < 0.7 ? 1 : 2;
        for (let k = 0; k < n; k++) {
          const date = addDays(weekStart, ri(0, 4));
          if (date > new Date()) continue;
          const equip = pick(EQUIP_TYPES);
          const car = pick(carPool[d.id]);
          const yard = pick(d.yards);
          const inspectionType = rand() < 0.65 ? "Routine" : rand() < 0.7 ? "Unannounced" : rand() < 0.6 ? "Complaint-Driven" : "Follow-up";

          // mild, explicit trend improvement built into the seed so Trends has
          // something to show — flagged in the UI as seed data, not a real result
          const trendLift = Math.min(6, w * 0.28);
          let interior = clamp(Math.round(d.baseline + trendLift + ri(-9, 9)), 35, 100);
          const glass = clamp(interior - ri(2, 16), 25, 100);
          const criticalDefect = rand() < d.criticalProb;
          const fail = interior < 70 || criticalDefect;

          let defectCategory = "None", rootCause = "N/A";
          if (fail || rand() < 0.18) {
            const pool = (fail && rand() < 0.7) ? DEFECT_WEIGHT_WEAK : DEFECT_CATEGORIES;
            defectCategory = pick(d.criticalProb > 0.08 ? DEFECT_WEIGHT_WEAK.concat(pool) : pool);
            const rcPool = d.id === "RI" ? ["Short Layover / Time Constraint", "Short Layover / Time Constraint", "Staffing Shortage", "High Ridership / Heavy Soiling"]
              : d.id === "SWS" ? ["Staffing Shortage", "Supply Shortage", "Training Gap", "High Ridership / Heavy Soiling"]
              : ROOT_CAUSES;
            rootCause = pick(rcPool);
          }
          const complaintLinked = inspectionType === "Complaint-Driven" || (fail && rand() < 0.32);
          const scheduledMin = equip.scheduledMin - (yard.includes("Blue Island") || d.id === "RI" ? 6 : 0); // pick-and-flip yards get less time
          const actualMin = clamp(scheduledMin + ri(-7, 5), 6, scheduledMin + 8);
          const employees = ri(1, 3);

          inspections.push({
            id: idCounter++, date: fmtDate(date), weekEnding: fmtDate(addDays(weekStart, 6)), month: monthLabel(date),
            district: d.id, yard, train: `${d.id}-${ri(100, 899)}`, car, equipType: equip.id,
            shift, team: pick(TEAMS), supervisor: SUPERVISORS[d.id], inspectionType,
            scheduledMin, actualMin, employees,
            interior, glass, overall: interior, criticalDefect, fail,
            defectCategory, rootCause, complaintLinked, repeatDefect: false,
          });
        }
      });
    });
  }
  inspections.sort((a, b) => a.date.localeCompare(b.date));

  // repeat-defect pass: same car + same defect category within 30 days of an earlier one
  const lastSeen = {};
  inspections.forEach(r => {
    if (r.defectCategory === "None") return;
    const key = `${r.car}|${r.defectCategory}`;
    const prevDate = lastSeen[key];
    if (prevDate && daysBetween(new Date(prevDate), new Date(r.date)) <= 30) r.repeatDefect = true;
    lastSeen[key] = r.date;
  });

  // corrective actions generated from failed inspections
  const today = new Date();
  const actions = [];
  let caId = 1;
  inspections.filter(r => r.fail).forEach(r => {
    const opened = new Date(r.date);
    const due = addDays(opened, 8);
    const daysSinceOpen = daysBetween(opened, today);
    let status, dateClosed = null, reinspectionResult = "Pending", effectivenessVerified = false;
    if (daysSinceOpen < 3) status = "Open";
    else if (daysSinceOpen < 8) status = rand() < 0.55 ? "In Progress" : "Open";
    else {
      const roll = rand();
      status = roll < 0.82 ? "Closed" : roll < 0.91 ? "In Progress" : "Open";
      if (status === "Closed") {
        dateClosed = addDays(opened, Math.min(daysSinceOpen, ri(3, 20)));
        reinspectionResult = rand() < 0.85 ? "Pass" : "Fail";
        effectivenessVerified = reinspectionResult === "Pass" && rand() < 0.9;
      }
    }
    const severity = r.criticalDefect ? "HIGH" : r.interior < 55 ? "HIGH" : "MED";
    actions.push({
      id: caId++, inspectionId: r.id, district: r.district, yard: r.yard, line: pick(DIST_LINES[r.district]),
      car: r.car, issue: `${r.defectCategory === "None" ? "Critical defect" : r.defectCategory} — ${r.interior}% interior score`,
      category: r.defectCategory, rootCause: r.rootCause, severity, owner: CA_OWNERS[r.district],
      status, dateOpened: r.date, due: fmtDate(due), dateClosed: dateClosed ? fmtDate(dateClosed) : null,
      reinspectionResult, effectivenessVerified,
    });
  });

  return { inspections, actions };
}

