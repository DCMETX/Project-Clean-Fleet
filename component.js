function toDistrict(code) {
  if (!code) return "SWS";
  if (code === "MDN" || code === "MDW" || code === "MD") return "MD";
  if (code.indexOf("UP") === 0) return "UP";
  if (code === "SWS" || code === "HC") return "SWS";
  return DIST_MAP[code] ? code : "SWS";
}
function parseDay(str) { return new Date((str || fmtDate(new Date())) + "T12:00:00"); }
const WINDOW_AREAS = ["Lower Level Windows", "Upper Level Windows"];
function mapRealData(docs, cas) {
  const inspections = docs.filter(d => d && d.date).map(d => {
    const dt = parseDay(d.date);
    const areas = (d.areas || []).filter(a => a.score !== null && a.score !== undefined);
    const win = areas.filter(a => WINDOW_AREAS.indexOf(a.name) !== -1);
    const glass = win.length ? Math.round(win.reduce((s, a) => s + a.score * 20, 0) / win.length) : null;
    const worst = areas.filter(a => a.score <= 3).sort((a, b) => a.score - b.score)[0];
    const interior = typeof d.gradePct === "number" ? Math.round(d.gradePct) : 0;
    const criticalDefect = (d.criticalCount || 0) > 0;
    const linkedCa = (cas || []).find(c => c.sourceInspectionId === d._id && (c.confirmedRootCause || c.probableCause));
    return {
      id: d._id, date: d.date, weekEnding: fmtDate(addDays(mostRecentMonday(dt), 6)), month: monthLabel(dt),
      district: toDistrict(d.district), line: d.district || "", yard: d.yard || "Unspecified yard", train: d.trainNumber || "", car: d.railcarNumber || "",
      equipType: "Not recorded", shift: d.shift || "AM", team: "—", supervisor: d.supervisor || "—", inspectionType: d.inspectionType || "Routine",
      scheduledMin: typeof d.scheduledMin === "number" ? d.scheduledMin : null,
      actualMin: typeof d.actualMin === "number" ? d.actualMin : null,
      employees: null,
      interior, glass: glass === null ? interior : glass, overall: interior, criticalDefect,
      fail: interior < 70 || criticalDefect,
      defectCategory: worst ? worst.name : "None",
      rootCause: worst ? (linkedCa ? (linkedCa.confirmedRootCause || linkedCa.probableCause) : "Not yet determined") : "N/A",
      complaintLinked: d.inspectionType === "Complaint-Driven" || !!d.jiraTicket,
      repeatDefect: false,
    };
  }).sort((a, b) => a.date.localeCompare(b.date));
  const lastSeen = {};
  inspections.forEach(r => {
    if (r.defectCategory === "None") return;
    const key = `${r.car}|${r.defectCategory}`;
    const prevDate = lastSeen[key];
    if (prevDate && daysBetween(new Date(prevDate), new Date(r.date)) <= 30) r.repeatDefect = true;
    lastSeen[key] = r.date;
  });
  const inspById = Object.fromEntries(inspections.map(r => [r.id, r]));
  const actions = (cas || []).map(c => {
    const src = inspById[c.sourceInspectionId];
    const closed = c.status === "Completed" || c.status === "Verified";
    return {
      id: c._id, inspectionId: c.sourceInspectionId, district: toDistrict(c.district), yard: src ? src.yard : "—", line: c.district || "",
      car: c.railcarNumber || "", issue: `${c.area || "Area"} (${c.severity || "exception"})${c.defectDescription ? " · " + c.defectDescription : ""}`,
      category: c.area || "Other", rootCause: c.confirmedRootCause || c.probableCause || "Not yet determined",
      severity: c.severity === "NO-GO" ? "HIGH" : "MED", owner: c.owner || "Unassigned",
      status: closed ? "Closed" : (c.status === "In Progress" ? "In Progress" : "Open"),
      dateOpened: c.assignedDate || fmtDate(new Date()), due: c.dueDate || "", dateClosed: closed ? (c.completionDate || c.verifiedDate || null) : null,
      reinspectionResult: c.reinspectionResult === "Pass" ? "Pass" : c.reinspectionResult ? "Fail" : "Pending",
      effectivenessVerified: !!c.effectivenessVerified,
    };
  });
  return { inspections, actions };
}

